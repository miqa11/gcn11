function drawPartyArt(container, art) {
  container.replaceChildren();
  container.hidden = !art;
  if (!art) return;
  if (art.startsWith("@")) {
    const namespace = "http://www.w3.org/2000/svg";
    const svg = document.createElementNS(namespace, "svg");
    const use = document.createElementNS(namespace, "use");
    svg.setAttribute("viewBox", "0 0 96 96");
    svg.setAttribute("focusable", "false");
    use.setAttribute("href", "/local-party-symbols.svg#" + art.slice(1));
    svg.append(use);
    container.append(svg);
    return;
  }
  const [main, detail] = art.split("+");
  const pictogram = document.createElement("span");
  pictogram.className = "pictogram";
  pictogram.textContent = main;
  container.append(pictogram);
  if (detail) {
    const badge = document.createElement("span");
    badge.className = "pictogram-detail";
    badge.textContent = detail;
    container.append(badge);
  }
}
